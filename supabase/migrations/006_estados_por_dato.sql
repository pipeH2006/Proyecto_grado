create or replace function puede_ver_proyecto(p_proyecto bigint) returns boolean
language sql stable security definer set search_path = public, pg_temp as $$
  select
    exists (
      select 1 from proyectos p
      join estado e on e.id = p.estado_actual_id
      where p.id = p_proyecto and e.codigo = 'FINALIZADO'
    )
    or es_autor(p_proyecto)
    or esta_asignado(p_proyecto)
    or es_gestor();
$$;

create or replace function buscar_antecedentes(
  consulta   text,
  p_programa smallint default null,
  limite     int default 20,
  p_periodo  text default null
)
returns table (
  id                 bigint,
  programa_id        smallint,
  titulo             text,
  resumen            text,
  palabras_clave     text[],
  periodo            text,
  fecha_finalizacion date,
  score              real
)
language sql stable security definer set search_path = public, pg_temp as $$
  with params as (
    select websearch_to_tsquery('spanish', consulta) as tsq,
           coalesce(trim(consulta), '') as raw
  ),
  finalizados as (
    select p.id, p.programa_id, p.titulo, p.resumen, p.palabras_clave,
           p.periodo, p.fecha_finalizacion, p.busqueda
    from proyectos p
    join estado e on e.id = p.estado_actual_id
    where e.codigo = 'FINALIZADO'
  ),
  fts as (
    select p.id,
           row_number() over (order by ts_rank(p.busqueda, params.tsq) desc, p.id) as rnk
    from finalizados p, params
    where (p_programa is null or p.programa_id = p_programa)
      and (p_periodo is null or p.periodo = p_periodo)
      and p.busqueda @@ params.tsq
    order by ts_rank(p.busqueda, params.tsq) desc, p.id
    limit greatest(limite, 1) * 5
  ),
  trgm as (
    select p.id,
           row_number() over (
             order by similarity(coalesce(p.titulo, '') || ' ' || coalesce(p.resumen, ''), params.raw) desc,
                      p.id
           ) as rnk
    from finalizados p, params
    where (p_programa is null or p.programa_id = p_programa)
      and (p_periodo is null or p.periodo = p_periodo)
      and params.raw <> ''
      and (coalesce(p.titulo, '') || ' ' || coalesce(p.resumen, '')) % params.raw
    order by similarity(coalesce(p.titulo, '') || ' ' || coalesce(p.resumen, ''), params.raw) desc, p.id
    limit greatest(limite, 1) * 5
  ),
  combinado as (
    select coalesce(f.id, t.id) as id,
           1.0 / (60 + coalesce(f.rnk, 1000000)) + 1.0 / (60 + coalesce(t.rnk, 1000000)) as score
    from fts f
    full outer join trgm t on t.id = f.id
  )
  select p.id, p.programa_id, p.titulo, p.resumen, p.palabras_clave,
         p.periodo, p.fecha_finalizacion, c.score::real
  from combinado c
  join proyectos p on p.id = c.id
  order by c.score desc, p.fecha_finalizacion desc nulls last
  limit greatest(limite, 1);
$$;

create policy proyectos_lectura_publica on proyectos
  for select to anon, authenticated using (
    exists (
      select 1 from estado e
      where e.id = proyectos.estado_actual_id and e.codigo = 'FINALIZADO'
    )
  );
create policy proyectos_edicion on proyectos
  for update to authenticated using (
    es_gestor() or (
      es_autor(id) and exists (
        select 1 from estado e
        where e.id = proyectos.estado_actual_id and e.codigo = 'BORRADOR'
      )
    )
  ) with check (es_gestor() or es_autor(id));
create policy persona_lectura on persona
  for select to anon, authenticated using (
    id = persona_actual()
    or es_gestor()
    or exists (
      select 1 from proyecto_autores pa
      join proyectos p on p.id = pa.proyecto_id
      join estado e on e.id = p.estado_actual_id
      where pa.persona_id = persona.id and e.codigo = 'FINALIZADO'
    )
  );

-- ---------------------------------------------------------------------------
-- Grafo de transiciones (documental; el avance real se hace insertando historia)
-- ---------------------------------------------------------------------------
insert into transicion_estado (estado_origen_id, estado_destino_id, rol_autorizado_id)
select o.id, d.id, r.id
from (values
  ('BORRADOR',      'RADICADO',      'ESTUDIANTE'),
  ('RADICADO',      'EN_REVISION',   'COORDINADOR'),
  ('EN_REVISION',   'APROBADO',      'COORDINADOR'),
  ('EN_REVISION',   'RECHAZADO',     'COORDINADOR'),
  ('APROBADO',      'EN_DESARROLLO', 'COORDINADOR'),
  ('EN_DESARROLLO', 'SUSTENTADO',    'COORDINADOR'),
  ('SUSTENTADO',    'FINALIZADO',    'COORDINADOR')
) as t(origen, destino, rol_codigo)
join estado o on o.codigo = t.origen
join estado d on d.codigo = t.destino
join rol r on r.codigo = t.rol_codigo;

-- ---------------------------------------------------------------------------
-- RLS de las tablas nuevas
-- ---------------------------------------------------------------------------
alter table estado               enable row level security;
alter table transicion_estado    enable row level security;
alter table proyecto_estado_hist enable row level security;

create policy estado_lectura on estado
  for select to anon, authenticated using (true);
create policy transicion_estado_lectura on transicion_estado
  for select to authenticated using (true);
create policy proyecto_estado_hist_lectura on proyecto_estado_hist
  for select to authenticated using (puede_ver_proyecto(proyecto_id));
create policy proyecto_estado_hist_alta on proyecto_estado_hist
  for insert to authenticated with check (puede_ver_proyecto(proyecto_id));

do $$
begin
  if exists (select 1 from pg_roles where rolname = 'authenticated') then
    grant select, insert, update, delete on all tables in schema public to authenticated;
    grant select on estado, transicion_estado to anon, authenticated;
    grant execute on all functions in schema public to anon, authenticated;
  end if;
end
$$;
