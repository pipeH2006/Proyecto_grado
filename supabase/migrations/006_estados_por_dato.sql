-- 006_estados_por_dato.sql
-- Reconciliacion con fase 1: el estado del proyecto deja de ser un enum y pasa a
-- ser un catalogo `estado`. La fuente de verdad del cambio es
-- `proyecto_estado_hist`: al insertar una fila ahi, un trigger sincroniza
-- `proyectos.estado_actual_id`. `transicion_estado` documenta que rol puede
-- ejecutar cada transicion.
--
-- Se conserva el concepto de borrador (no existe en fase 1) para no romper el
-- flujo de alta/edicion que el RLS ya protege.

create table estado (
  id       smallint generated by default as identity primary key,
  codigo   varchar(30) not null unique,
  nombre   varchar(80) not null,
  orden    smallint not null,
  es_final boolean not null default false
);

insert into estado (codigo, nombre, orden, es_final) values
  ('BORRADOR',      'Borrador',               0, false),
  ('RADICADO',      'Radicado',               1, false),
  ('EN_REVISION',   'En revision',            2, false),
  ('APROBADO',      'Anteproyecto aprobado',  3, false),
  ('EN_DESARROLLO', 'En desarrollo',          4, false),
  ('SUSTENTADO',    'Sustentado',             5, false),
  ('FINALIZADO',    'Finalizado',             6, true),
  ('RECHAZADO',     'Rechazado',              7, true),
  ('CANCELADO',     'Cancelado',              8, true);

-- Acceso al id de un estado por su codigo (para defaults y app).
create or replace function estado_id(p_codigo text) returns smallint
language sql stable security definer set search_path = public, pg_temp as $$
  select id from estado where codigo = p_codigo;
$$;

create table transicion_estado (
  id                serial primary key,
  estado_origen_id  smallint not null references estado (id) on update cascade,
  estado_destino_id smallint not null references estado (id) on update cascade,
  rol_autorizado_id smallint not null references rol (id) on update cascade,
  unique (estado_origen_id, estado_destino_id, rol_autorizado_id),
  check (estado_origen_id <> estado_destino_id)
);

create table proyecto_estado_hist (
  id          serial primary key,
  proyecto_id integer not null references proyectos (id) on delete cascade,
  estado_id   smallint not null references estado (id) on update cascade,
  fecha       timestamptz not null default now(),
  usuario_id  uuid references persona (id) on delete set null,
  observacion text
);
create index idx_hist_proyecto on proyecto_estado_hist (proyecto_id, fecha desc);

-- ---------------------------------------------------------------------------
-- proyectos: enum estado -> estado_actual_id
-- ---------------------------------------------------------------------------
alter table proyectos add column estado_actual_id smallint references estado (id);

update proyectos p
   set estado_actual_id = e.id
  from estado e
 where e.codigo = case p.estado
   when 'borrador'      then 'BORRADOR'
   when 'en_evaluacion' then 'EN_REVISION'
   when 'aprobado'      then 'APROBADO'
   when 'rechazado'     then 'RECHAZADO'
   when 'finalizado'    then 'FINALIZADO'
   when 'archivado'     then 'CANCELADO'
 end;

alter table proyectos alter column estado_actual_id set not null;
alter table proyectos alter column estado_actual_id set default estado_id('BORRADOR');

-- Bitacora inicial de los proyectos existentes.
insert into proyecto_estado_hist (proyecto_id, estado_id, fecha, usuario_id)
select p.id, p.estado_actual_id, p.creado_en, p.creado_por from proyectos p;

-- Al insertar historial, el estado actual del proyecto sigue a la bitacora.
create or replace function fn_sync_estado_actual() returns trigger
language plpgsql security definer set search_path = public, pg_temp as $$
begin
  update proyectos set estado_actual_id = new.estado_id where id = new.proyecto_id;
  return new;
end;
$$;

create trigger trg_hist_sync_estado
  after insert on proyecto_estado_hist
  for each row execute function fn_sync_estado_actual();

-- Todo proyecto nuevo registra su estado inicial en la bitacora.
create or replace function trg_proyecto_estado_inicial() returns trigger
language plpgsql security definer set search_path = public, pg_temp as $$
begin
  insert into proyecto_estado_hist (proyecto_id, estado_id, usuario_id)
  values (new.id, new.estado_actual_id, new.creado_por);
  return new;
end;
$$;

create trigger trg_proyecto_estado_inicial
  after insert on proyectos
  for each row execute function trg_proyecto_estado_inicial();

