create or replace function set_actualizado_en() returns trigger
language plpgsql as $$
begin
  new.actualizado_en := now();
  return new;
end;
$$;

create trigger trg_personas_actualizado
  before update on personas for each row execute function set_actualizado_en();
create trigger trg_proyectos_actualizado
  before update on proyectos for each row execute function set_actualizado_en();

-- RF-02: mantener el tsvector de busqueda (titulo + resumen + palabras clave).
create or replace function actualizar_busqueda() returns trigger
language plpgsql as $$
begin
  new.busqueda := to_tsvector(
    'spanish'::regconfig,
    coalesce(new.titulo, '') || ' ' || coalesce(new.resumen, '') || ' ' ||
    coalesce(array_to_string(new.palabras_clave, ' '), '')
  );
  return new;
end;
$$;

create trigger trg_proyectos_busqueda
  before insert or update of titulo, resumen, palabras_clave on proyectos
  for each row execute function actualizar_busqueda();

-- Quien crea el proyecto queda como autor principal (security definer: evita el
-- problema de huevo/gallina del RLS, pues aun no existe fila en proyecto_autores).
create or replace function agregar_autor_creador() returns trigger
language plpgsql security definer set search_path = public, pg_temp as $$
begin
  if new.creado_por is not null then
    insert into proyecto_autores (proyecto_id, persona_id, es_principal, orden)
    values (new.id, new.creado_por, true, 1)
    on conflict (proyecto_id, persona_id) do nothing;
  end if;
  return new;
end;
$$;

create trigger trg_proyecto_autor_creador
  after insert on proyectos for each row execute function agregar_autor_creador();

-- RF-08: la observacion no cambia su contenido; solo estado/cierre.
create or replace function trg_observacion_inmutable() returns trigger
language plpgsql as $$
begin
  if new.proyecto_id   is distinct from old.proyecto_id
     or new.texto        is distinct from old.texto
     or new.ronda_id     is distinct from old.ronda_id
     or new.asignacion_id is distinct from old.asignacion_id
     or new.severidad    is distinct from old.severidad
     or new.creada_por   is distinct from old.creada_por
     or new.creada_en    is distinct from old.creada_en then
    raise exception
      'Las observaciones son inmutables: solo puede cambiar estado, cerrada_por y cerrada_en';
  end if;
  return new;
end;
$$;

create trigger trg_observacion_inmutable
  before update on observaciones for each row execute function trg_observacion_inmutable();

-- Coherencia proyecto_id <-> ronda/asignacion.
create or replace function validar_observacion_proyecto() returns trigger
language plpgsql as $$
begin
  if new.ronda_id is not null
     and (select proyecto_id from rondas where id = new.ronda_id) is distinct from new.proyecto_id then
    raise exception 'proyecto_id no coincide con la ronda %', new.ronda_id;
  end if;
  if new.asignacion_id is not null
     and (select proyecto_id from asignaciones where id = new.asignacion_id) is distinct from new.proyecto_id then
    raise exception 'proyecto_id no coincide con la asignacion %', new.asignacion_id;
  end if;
  return new;
end;
$$;

create trigger trg_observacion_proyecto
  before insert or update of ronda_id, asignacion_id, proyecto_id on observaciones
  for each row execute function validar_observacion_proyecto();

-- Grafo de transiciones (RF-06). El gestor puede corregir; los demas siguen:
--   estudiante: pendiente -> en_correccion
--   evaluador:  en_correccion -> solucionada | no_aplica,  solucionada -> pendiente (reabrir)
create or replace function validar_transicion_observacion() returns trigger
language plpgsql as $$
declare
  v_actor uuid := persona_actual();
begin
  if new.estado is distinct from old.estado then
    if v_actor is not null and not es_gestor() then
      if not (
        (old.estado = 'pendiente'     and new.estado = 'en_correccion')
        or (old.estado = 'en_correccion' and new.estado in ('solucionada', 'no_aplica'))
        or (old.estado = 'solucionada'   and new.estado = 'pendiente')
      ) then
        raise exception 'Transicion de estado no permitida: % -> %', old.estado, new.estado;
      end if;
    end if;

    if new.estado in ('solucionada', 'no_aplica') then
      new.cerrada_en := coalesce(new.cerrada_en, now());
      new.cerrada_por := coalesce(new.cerrada_por, v_actor);
    else
      new.cerrada_en := null;
      new.cerrada_por := null;
    end if;
  end if;
  return new;
end;
$$;

create trigger trg_observacion_transicion
  before update on observaciones for each row execute function validar_transicion_observacion();

-- Bitacora: registra alta y cambios de estado (security definer para saltar RLS).
create or replace function registrar_evento_observacion() returns trigger
language plpgsql security definer set search_path = public, pg_temp as $$
begin
  insert into eventos_observacion (observacion_id, estado_anterior, estado_nuevo, actor_id)
  values (
    new.id,
    case when tg_op = 'UPDATE' then old.estado else null end,
    new.estado,
    coalesce(persona_actual(), new.creada_por, new.cerrada_por)
  );
  return new;
end;
$$;

create trigger trg_observacion_evento
  after insert or update of estado on observaciones
  for each row execute function registrar_evento_observacion();

-- Historial inmutable: prohibido DELETE.
create or replace function bloquear_delete() returns trigger
language plpgsql as $$
begin
  raise exception 'DELETE prohibido en %: el historial es inmutable', tg_table_name;
end;
$$;

create trigger trg_observacion_no_delete
  before delete on observaciones for each row execute function bloquear_delete();
create trigger trg_evento_no_delete
  before delete on eventos_observacion for each row execute function bloquear_delete();

-- Provision de persona al primer login (Supabase Auth): vincula por email al
-- autor historico o crea una persona nueva.
do $$
begin
  if to_regclass('auth.users') is not null then
    execute $fn$
      create or replace function manejar_nuevo_usuario() returns trigger
      language plpgsql security definer set search_path = public, pg_temp as $body$
      declare v_persona uuid;
      begin
        select id into v_persona
        from personas
        where usuario_id is null and email = new.email
        limit 1;

        if v_persona is not null then
          update personas
             set usuario_id = new.id, actualizado_en = now()
           where id = v_persona;
        else
          insert into personas (usuario_id, nombres, apellidos, email)
          values (
            new.id,
            coalesce(new.raw_user_meta_data->>'given_name',
                     new.raw_user_meta_data->>'name',
                     split_part(coalesce(new.email, 'usuario'), '@', 1)),
            coalesce(new.raw_user_meta_data->>'family_name', ''),
            new.email
          )
          on conflict (usuario_id) do nothing
          returning id into v_persona;

          if v_persona is null then
            select id into v_persona from personas where usuario_id = new.id;
          end if;
        end if;

        -- Todo usuario institucional entra como estudiante; coordinador/admin se
        -- asignan despues. Sin este rol, el RLS impediria crear anteproyectos.
        if v_persona is not null then
          insert into roles_persona (persona_id, programa_id, rol)
          values (v_persona, null, 'estudiante')
          on conflict do nothing;
        end if;

        return new;
      end;
      $body$;
    $fn$;

    execute 'drop trigger if exists on_auth_user_created on auth.users';
    execute 'create trigger on_auth_user_created
               after insert on auth.users
               for each row execute function manejar_nuevo_usuario()';
  end if;
end;
$$;

