-- 001_schema_inicial.sql
-- Esquema base del sistema de anteproyectos / repositorio de proyectos de grado.
-- Cubre MVP end-to-end: RF-01 (registrar), RF-02 (buscar), RF-05 (observaciones por ronda),
-- RF-06 (estado por observacion) y RF-08 (historial inmutable via triggers).
-- Fase 2 (pgvector, embeddings, buscar_hibrido) se difiere a la migracion 002.

create extension if not exists pg_trgm;
create extension if not exists btree_gist;

-- ---------------------------------------------------------------------------
-- Enums
-- ---------------------------------------------------------------------------
create type rol_usuario as enum ('estudiante', 'evaluador', 'coordinador', 'admin');

create type estado_proyecto as enum (
  'borrador', 'en_evaluacion', 'aprobado', 'rechazado', 'finalizado', 'archivado'
);

-- Exactamente los estados descritos en AGENTS.md.
create type estado_observacion as enum ('pendiente', 'en_correccion', 'solucionada', 'no_aplica');

create type severidad as enum ('baja', 'media', 'alta');

create type tipo_documento as enum ('anteproyecto', 'anexo', 'evidencia', 'acta', 'otro');

-- ---------------------------------------------------------------------------
-- Programas academicos (smallint para igualar la firma buscar_antecedentes)
-- ---------------------------------------------------------------------------
create table programas (
  id        smallint generated by default as identity primary key,
  codigo    text not null unique,
  nombre    text not null,
  facultad  text,
  activo    boolean not null default true,
  creado_en timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- Personas != auth.users. Los autores historicos no tienen cuenta:
-- usuario_id es nullable y se vincula en el primer login (ver trigger final).
-- ---------------------------------------------------------------------------
create table personas (
  id            uuid primary key default gen_random_uuid(),
  usuario_id    uuid unique references auth.users (id) on delete set null,
  nombres       text not null,
  apellidos     text not null default '',
  email         text unique,
  documento     text,
  telefono      text,
  creado_en     timestamptz not null default now(),
  actualizado_en timestamptz not null default now()
);

-- Roles por programa: una persona puede ser evaluadora en un programa y
-- coordinadora en otro. programa_id NULL = rol global (p. ej. admin).
create table roles_persona (
  id         bigint generated always as identity primary key,
  persona_id uuid not null references personas (id) on delete cascade,
  programa_id smallint references programas (id) on delete cascade,
  rol        rol_usuario not null,
  creado_en  timestamptz not null default now()
);
create unique index roles_persona_unico
  on roles_persona (persona_id, coalesce(programa_id, -1), rol);

-- ---------------------------------------------------------------------------
-- Tesauro (vocabulario controlado por el coordinador)
-- ---------------------------------------------------------------------------
create table tesauro (
  id          bigint generated always as identity primary key,
  programa_id smallint references programas (id) on delete cascade,
  termino     text not null,
  sinonimos   text[] not null default '{}',
  descripcion text,
  activo      boolean not null default true,
  creado_en   timestamptz not null default now()
);
create unique index tesauro_termino_unico
  on tesauro (coalesce(programa_id, -1), lower(termino));

-- ---------------------------------------------------------------------------
-- Proyectos: una sola tabla para catalogo publico y flujo de anteproyectos,
-- diferenciada por estado (borrador -> ... -> finalizado).
-- ---------------------------------------------------------------------------
create table proyectos (
  id                 bigint generated always as identity primary key,
  programa_id        smallint not null references programas (id),
  titulo             text not null,
  resumen            text,
  palabras_clave     text[] not null default '{}',
  estado             estado_proyecto not null default 'borrador',
  periodo            text,
  fecha_sustentacion date,
  fecha_finalizacion date,
  creado_por         uuid references personas (id),
  creado_en          timestamptz not null default now(),
  actualizado_en     timestamptz not null default now(),
  -- tsvector para RF-02 (full-text en espanol). Se mantiene por trigger porque
  -- array_to_string() no es IMMUTABLE y no puede usarse en columna generada.
  busqueda tsvector
);
create index proyectos_busqueda_idx on proyectos using gin (busqueda);
create index proyectos_titulo_trgm_idx on proyectos using gin (titulo gin_trgm_ops);
create index proyectos_resumen_trgm_idx on proyectos using gin (resumen gin_trgm_ops);
create index proyectos_estado_idx on proyectos (estado);

-- Autores (1..n por proyecto; soporta coautoria y autores historicos).
create table proyecto_autores (
  id          bigint generated always as identity primary key,
  proyecto_id bigint not null references proyectos (id) on delete cascade,
  persona_id  uuid not null references personas (id) on delete cascade,
  orden       smallint not null default 1,
  es_principal boolean not null default false,
  creado_en   timestamptz not null default now(),
  unique (proyecto_id, persona_id)
);

create table proyecto_tesauro (
  proyecto_id bigint not null references proyectos (id) on delete cascade,
  tesauro_id  bigint not null references tesauro (id) on delete cascade,
  primary key (proyecto_id, tesauro_id)
);

-- ---------------------------------------------------------------------------
-- Rondas de evaluacion (solo una abierta por proyecto a la vez)
-- ---------------------------------------------------------------------------
create table rondas (
  id          bigint generated always as identity primary key,
  proyecto_id bigint not null references proyectos (id) on delete cascade,
  numero      smallint not null,
  abierta_por uuid references personas (id),
  abierta_en  timestamptz not null default now(),
  cerrada_en  timestamptz,
  unique (proyecto_id, numero)
);
create unique index rondas_una_abierta_por_proyecto
  on rondas (proyecto_id) where cerrada_en is null;

-- ---------------------------------------------------------------------------
-- Asignaciones con vigencia daterange. Cambiar de evaluador = cerrar el rango
-- y abrir otro; NUNCA un booleano "activo". La exclusion impide solapes.
-- ---------------------------------------------------------------------------
create table asignaciones (
  id          bigint generated always as identity primary key,
  proyecto_id bigint not null references proyectos (id) on delete cascade,
  persona_id  uuid not null references personas (id) on delete cascade,
  rol         rol_usuario not null default 'evaluador',
  vigencia    daterange not null default daterange(current_date, null, '[)'),
  creada_por  uuid references personas (id),
  creada_en   timestamptz not null default now(),
  constraint asignacion_sin_solape exclude using gist (
    proyecto_id with =,
    persona_id with =,
    vigencia with &&
  ),
  constraint asignacion_rol_evaluador check (rol in ('evaluador', 'coordinador', 'admin'))
);

-- ---------------------------------------------------------------------------
-- Observaciones: inmutables (texto/ronda/asignacion/severidad).
-- ---------------------------------------------------------------------------
create table observaciones (
  id            bigint generated always as identity primary key,
  proyecto_id   bigint not null references proyectos (id) on delete cascade,
  ronda_id      bigint not null references rondas (id),
  asignacion_id bigint not null references asignaciones (id),
  texto         text not null,
  severidad     severidad not null default 'media',
  estado        estado_observacion not null default 'pendiente',
  creada_por    uuid not null references personas (id),
  creada_en     timestamptz not null default now(),
  cerrada_por   uuid references personas (id),
  cerrada_en    timestamptz,
  -- Coherencia: solo los estados terminales tienen cerrada_en.
  constraint observacion_cierre_coherente
    check ((estado in ('solucionada', 'no_aplica')) = (cerrada_en is not null))
);
create index observaciones_proyecto_idx on observaciones (proyecto_id);
create index observaciones_estado_idx on observaciones (estado);

create table respuestas_observacion (
  id            bigint generated always as identity primary key,
  observacion_id bigint not null references observaciones (id) on delete restrict,
  autor_id      uuid not null references personas (id),
  texto         text not null,
  creada_en     timestamptz not null default now()
);
create index respuestas_observacion_idx on respuestas_observacion (observacion_id);

-- ---------------------------------------------------------------------------
-- Documentos (PDFs en Supabase Storage; la ruta vive aqui, no el binario).
-- ---------------------------------------------------------------------------
create table documentos (
  id            bigint generated always as identity primary key,
  proyecto_id   bigint not null references proyectos (id) on delete cascade,
  respuesta_id  bigint references respuestas_observacion (id) on delete set null,
  tipo          tipo_documento not null default 'anexo',
  storage_bucket text not null default 'documentos',
  storage_path  text not null,
  nombre_original text not null,
  mime_type     text,
  tamano_bytes  bigint,
  subido_por    uuid references personas (id),
  creado_en     timestamptz not null default now(),
  unique (storage_bucket, storage_path)
);
create index documentos_proyecto_idx on documentos (proyecto_id);

-- Bitacora append-only de cambios de estado (RF-08). No se borra ni actualiza.
create table eventos_observacion (
  id              bigint generated always as identity primary key,
  observacion_id  bigint not null references observaciones (id) on delete restrict,
  estado_anterior estado_observacion,
  estado_nuevo    estado_observacion not null,
  actor_id        uuid references personas (id),
  nota            text,
  ocurrido_en     timestamptz not null default now()
);
create index eventos_observacion_idx on eventos_observacion (observacion_id);

-- ===========================================================================
-- Funciones de ayuda (security definer: evitan recursion de RLS y exponen solo
-- lo necesario; siempre fijan search_path).
-- ===========================================================================
create or replace function persona_actual() returns uuid
language sql stable security definer set search_path = public, pg_temp as $$
  select id from personas where usuario_id = auth.uid();
$$;

create or replace function tiene_rol(p_rol rol_usuario) returns boolean
language sql stable security definer set search_path = public, pg_temp as $$
  select exists (
    select 1 from roles_persona rp
    where rp.persona_id = persona_actual() and rp.rol = p_rol
  );
$$;

create or replace function es_autor(p_proyecto bigint) returns boolean
language sql stable security definer set search_path = public, pg_temp as $$
  select exists (
    select 1 from proyecto_autores pa
    where pa.proyecto_id = p_proyecto and pa.persona_id = persona_actual()
  );
$$;

create or replace function esta_asignado(p_proyecto bigint) returns boolean
language sql stable security definer set search_path = public, pg_temp as $$
  select exists (
    select 1 from asignaciones a
    where a.proyecto_id = p_proyecto
      and a.persona_id = persona_actual()
      and a.vigencia @> current_date
  );
$$;

create or replace function es_gestor() returns boolean
language sql stable security definer set search_path = public, pg_temp as $$
  select tiene_rol('coordinador') or tiene_rol('admin');
$$;

create or replace function proyecto_de_observacion(p_observacion bigint) returns bigint
language sql stable security definer set search_path = public, pg_temp as $$
  select proyecto_id from observaciones where id = p_observacion;
$$;

create or replace function puede_ver_proyecto(p_proyecto bigint) returns boolean
language sql stable security definer set search_path = public, pg_temp as $$
  select
    exists (select 1 from proyectos p where p.id = p_proyecto and p.estado = 'finalizado')
    or es_autor(p_proyecto)
    or esta_asignado(p_proyecto)
    or es_gestor();
$$;

-- Busqueda de antecedentes: full-text + trigramas combinados con RRF (k=60).
create or replace function buscar_antecedentes(
  consulta   text,
  p_programa smallint default null,
  limite     int default 20,
  p_periodo  text default null
)
returns table (
  id                 bigint,
  programa_id        smallint,
  titulo             text,
  resumen            text,
  palabras_clave     text[],
  periodo            text,
  fecha_finalizacion date,
  score              real
)
language sql stable security definer set search_path = public, pg_temp as $$
  with params as (
    select websearch_to_tsquery('spanish', consulta) as tsq,
           coalesce(trim(consulta), '') as raw
  ),
  fts as (
    select p.id,
           row_number() over (order by ts_rank(p.busqueda, params.tsq) desc, p.id) as rnk
    from proyectos p, params
    where p.estado = 'finalizado'
      and (p_programa is null or p.programa_id = p_programa)
      and (p_periodo is null or p.periodo = p_periodo)
      and p.busqueda @@ params.tsq
    order by ts_rank(p.busqueda, params.tsq) desc, p.id
    limit greatest(limite, 1) * 5
  ),
  trgm as (
    select p.id,
           row_number() over (
             order by similarity(coalesce(p.titulo, '') || ' ' || coalesce(p.resumen, ''), params.raw) desc,
                      p.id
           ) as rnk
    from proyectos p, params
    where p.estado = 'finalizado'
      and (p_programa is null or p.programa_id = p_programa)
      and (p_periodo is null or p.periodo = p_periodo)
      and params.raw <> ''
      and (coalesce(p.titulo, '') || ' ' || coalesce(p.resumen, '')) % params.raw
    order by similarity(coalesce(p.titulo, '') || ' ' || coalesce(p.resumen, ''), params.raw) desc, p.id
    limit greatest(limite, 1) * 5
  ),
  combinado as (
    select coalesce(f.id, t.id) as id,
           1.0 / (60 + coalesce(f.rnk, 1000000)) + 1.0 / (60 + coalesce(t.rnk, 1000000)) as score
    from fts f
    full outer join trgm t on t.id = f.id
  )
  select p.id, p.programa_id, p.titulo, p.resumen, p.palabras_clave,
         p.periodo, p.fecha_finalizacion, c.score::real
  from combinado c
  join proyectos p on p.id = c.id
  order by c.score desc, p.fecha_finalizacion desc nulls last
  limit greatest(limite, 1);
$$;

