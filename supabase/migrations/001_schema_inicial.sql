-- Catalogos de lectura publica.
create policy programas_lectura on programas
  for select to anon, authenticated using (true);
create policy tesauro_lectura on tesauro
  for select to anon, authenticated using (activo or es_gestor());
create policy tesauro_gestion on tesauro
  for all to authenticated using (es_gestor()) with check (es_gestor());

-- Personas: uno mismo, gestores y autores de proyectos finalizados (para el
-- catalogo publico). Escritura solo de gestores o del propio registro.
create policy personas_lectura on personas
  for select to anon, authenticated using (
    id = persona_actual()
    or es_gestor()
    or exists (
      select 1 from proyecto_autores pa
      join proyectos p on p.id = pa.proyecto_id
      where pa.persona_id = personas.id and p.estado = 'finalizado'
    )
  );
create policy personas_escritura on personas
  for all to authenticated using (id = persona_actual() or es_gestor())
  with check (id = persona_actual() or es_gestor());

create policy roles_persona_lectura on roles_persona
  for select to authenticated using (persona_id = persona_actual() or es_gestor());
create policy roles_persona_gestion on roles_persona
  for all to authenticated using (es_gestor()) with check (es_gestor());

-- Proyectos: catalogo publico de finalizados; autores/asignados los propios;
-- gestores todo. Alta como borrador reservada a estudiantes y gestores.
create policy proyectos_lectura_publica on proyectos
  for select to anon, authenticated using (estado = 'finalizado');
create policy proyectos_lectura_implicados on proyectos
  for select to authenticated using (es_autor(id) or esta_asignado(id) or es_gestor());
create policy proyectos_alta on proyectos
  for insert to authenticated with check (
    es_gestor() or tiene_rol('estudiante')
  );
create policy proyectos_edicion on proyectos
  for update to authenticated using (
    es_gestor() or (es_autor(id) and estado = 'borrador')
  ) with check (es_gestor() or es_autor(id));
create policy proyectos_borrado on proyectos
  for delete to authenticated using (es_gestor());

create policy proyecto_autores_lectura on proyecto_autores
