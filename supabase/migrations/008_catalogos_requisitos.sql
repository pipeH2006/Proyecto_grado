  using (es_gestor() or es_autor(proyecto_id))
  with check (es_gestor() or es_autor(proyecto_id));

-- ---------------------------------------------------------------------------
-- 9. Vistas (respetan la RLS del que consulta)
-- ---------------------------------------------------------------------------
create view v_requisitos_pendientes with (security_invoker = true) as
select p.id as proyecto_id, p.titulo, m.nombre as modalidad, e.nombre as etapa,
       r.nombre as requisito, ec.nombre as estado_cumplimiento, mr.obligatorio
from proyectos p
join modalidad m on m.id = p.modalidad_id
join proyecto_requisito pr on pr.proyecto_id = p.id
join modalidad_requisito mr on mr.id = pr.modalidad_requisito_id
join requisito r on r.id = mr.requisito_id
join etapa e on e.id = mr.etapa_id
join estado_cumplimiento ec on ec.id = pr.estado_cumplimiento_id
where ec.codigo <> 'APROBADO' and mr.obligatorio = true
order by p.id, e.orden, mr.orden;

create view v_resumen_periodo with (security_invoker = true) as
select pa.anio, pa.semestre, m.nombre as modalidad, es.nombre as estado,
       count(*) as total_proyectos
from proyectos p
join periodo_academico pa on pa.id = p.periodo_id
join modalidad m on m.id = p.modalidad_id
join estado es on es.id = p.estado_actual_id
group by pa.anio, pa.semestre, m.nombre, es.nombre;

