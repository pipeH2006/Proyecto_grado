create table modalidad_requisito (
  id             bigint generated always as identity primary key,
  modalidad_id   smallint not null references modalidad (id) on update cascade,
  requisito_id   bigint   not null references requisito (id) on update cascade,
  etapa_id       smallint not null references etapa (id) on update cascade,
  obligatorio    boolean  not null default true,
  orden          smallint not null default 1,
  vigencia_desde date     not null,
  vigencia_hasta date,
  vigencia       daterange generated always as
                   (daterange(vigencia_desde, vigencia_hasta, '[)')) stored,
  check (vigencia_hasta is null or vigencia_hasta >= vigencia_desde),
  constraint modreq_sin_solape exclude using gist (
    modalidad_id with =,
    requisito_id with =,
    vigencia     with &&
  )
);
create index idx_modreq_busqueda
  on modalidad_requisito (modalidad_id, vigencia_desde, vigencia_hasta);

-- ---------------------------------------------------------------------------
-- 5. proyectos: periodo texto -> FK, y modalidad
-- ---------------------------------------------------------------------------
alter table proyectos
  add column modalidad_id    smallint references modalidad (id) on update cascade,
  add column periodo_id      smallint references periodo_academico (id) on update cascade,
  add column fecha_radicacion date;

-- Backfill: periodos que falten a partir del texto viejo, y luego la FK.
insert into periodo_academico (anio, semestre)
select distinct split_part(periodo, '-', 1)::smallint,
                split_part(periodo, '-', 2)::smallint
  from proyectos
 where periodo ~ '^[0-9]{4}-[12]$'
on conflict (anio, semestre) do nothing;

update proyectos p
   set periodo_id = pa.id
  from periodo_academico pa
 where p.periodo ~ '^[0-9]{4}-[12]$'
   and pa.anio = split_part(p.periodo, '-', 1)::smallint
   and pa.semestre = split_part(p.periodo, '-', 2)::smallint;

-- Proyectos sin periodo valido: el mas reciente del catalogo.
update proyectos
   set periodo_id = (select id from periodo_academico
                     order by anio desc, semestre desc limit 1)
 where periodo_id is null;

update proyectos
   set modalidad_id = (select id from modalidad where codigo = 'MONOGRAFIA')
 where modalidad_id is null;

alter table proyectos
  alter column modalidad_id set not null,
  alter column periodo_id   set not null,
  add constraint proyecto_fechas_orden check (
    fecha_sustentacion is null
    or fecha_radicacion is null
    or fecha_sustentacion >= fecha_radicacion
  );

create index idx_proyecto_modalidad on proyectos (modalidad_id);
create index idx_proyecto_periodo   on proyectos (periodo_id);

alter table proyectos drop column periodo;

-- buscar_antecedentes: el periodo vuelve a ser texto, derivado del catalogo.
create or replace function buscar_antecedentes(
  consulta   text,
  p_programa smallint default null,
  limite     int default 20,
  p_periodo  text default null
)
returns table (
  id                 bigint,
  programa_id        smallint,
  titulo             text,
  resumen            text,
  palabras_clave     text[],
  periodo            text,
  fecha_finalizacion date,
  score              real
)
language sql stable security definer set search_path = public, pg_temp as $$
  with params as (
    select websearch_to_tsquery('spanish', consulta) as tsq,
           coalesce(trim(consulta), '') as raw
  ),
  finalizados as (
    select p.id, p.programa_id, p.titulo, p.resumen, p.palabras_clave,
           (pa.anio::text || '-' || pa.semestre::text) as periodo,
           p.fecha_finalizacion, p.busqueda
    from proyectos p
    join estado e on e.id = p.estado_actual_id
    join periodo_academico pa on pa.id = p.periodo_id
    where e.codigo = 'FINALIZADO'
  ),
  fts as (
    select p.id,
           row_number() over (order by ts_rank(p.busqueda, params.tsq) desc, p.id) as rnk
    from finalizados p, params
    where (p_programa is null or p.programa_id = p_programa)
      and (p_periodo is null or p.periodo = p_periodo)
      and p.busqueda @@ params.tsq
    order by ts_rank(p.busqueda, params.tsq) desc, p.id
    limit greatest(limite, 1) * 5
  ),
  trgm as (
    select p.id,
           row_number() over (
             order by similarity(coalesce(p.titulo, '') || ' ' || coalesce(p.resumen, ''), params.raw) desc,
                      p.id
           ) as rnk
    from finalizados p, params
    where (p_programa is null or p.programa_id = p_programa)
      and (p_periodo is null or p.periodo = p_periodo)
      and params.raw <> ''
      and (coalesce(p.titulo, '') || ' ' || coalesce(p.resumen, '')) % params.raw
    order by similarity(coalesce(p.titulo, '') || ' ' || coalesce(p.resumen, ''), params.raw) desc, p.id
    limit greatest(limite, 1) * 5
  ),
  combinado as (
    select coalesce(f.id, t.id) as id,
           1.0 / (60 + coalesce(f.rnk, 1000000)) + 1.0 / (60 + coalesce(t.rnk, 1000000)) as score
    from fts f
    full outer join trgm t on t.id = f.id
  )
  select p.id, p.programa_id, p.titulo, p.resumen, p.palabras_clave,
         p.periodo, p.fecha_finalizacion, c.score::real
  from combinado c
  join finalizados p on p.id = c.id
  order by c.score desc, p.fecha_finalizacion desc nulls last
  limit greatest(limite, 1);
$$;

-- ---------------------------------------------------------------------------
-- 6. Cumplimiento por proyecto
-- ---------------------------------------------------------------------------
create table proyecto_requisito (
  id                     bigint generated always as identity primary key,
  proyecto_id            bigint not null references proyectos (id) on delete cascade,
  modalidad_requisito_id bigint not null references modalidad_requisito (id) on update cascade,
  estado_cumplimiento_id smallint not null references estado_cumplimiento (id) on update cascade,
  fecha_cumplimiento     date,
  verificado_por         uuid references persona (id) on delete set null,
  observacion            text,
  unique (proyecto_id, modalidad_requisito_id)
);
create index idx_proyreq_estado on proyecto_requisito (estado_cumplimiento_id);

-- ---------------------------------------------------------------------------
-- 7. documentos: hash, version y enlace al requisito
-- ---------------------------------------------------------------------------
alter table documentos
  add column hash_sha256          char(64),
  add column version              smallint not null default 1,
  add column proyecto_requisito_id bigint references proyecto_requisito (id) on delete set null;

create unique index documentos_req_version_unico
  on documentos (proyecto_requisito_id, version)
  where proyecto_requisito_id is not null;

