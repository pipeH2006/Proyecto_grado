-- 008_catalogos_requisitos.sql
-- Fase 3 de la reconciliacion con fase 1.
--
--   * Catalogo de periodos academicos y modalidades; `proyectos` pasa de un
--     `periodo` de texto libre a `periodo_id`/`modalidad_id` (FK).
--   * Motor de requisitos: requisito, etapa, modalidad_requisito (con vigencia
--     daterange), estado_cumplimiento y proyecto_requisito (cumplimiento por
--     proyecto).
--   * `documentos` (ya existente, respaldada por Storage) suma hash_sha256,
--     version y proyecto_requisito_id: el anteproyecto pasa a ser el requisito
--     'ANTEPROYECTO'. Se conserva una sola tabla de documentos.
--   * Vistas v_requisitos_pendientes y v_resumen_periodo.

create extension if not exists btree_gist;

-- ---------------------------------------------------------------------------
-- 1. Periodo academico
-- ---------------------------------------------------------------------------
create table periodo_academico (
  id           smallint generated by default as identity primary key,
  anio         smallint not null,
  semestre     smallint not null check (semestre in (1, 2)),
  fecha_inicio date,
  fecha_fin    date,
  unique (anio, semestre),
  check (fecha_fin is null or fecha_inicio is null or fecha_fin >= fecha_inicio)
);

