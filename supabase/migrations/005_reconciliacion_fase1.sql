-- 005_reconciliacion_fase1.sql
-- Reconciliacion con esquema_fase1.sql conservando Supabase Auth, la RLS y el
-- workflow de observaciones (RF-05..RF-08).
--
-- Cambios:
--   * La tabla de identidad pasa a llamarse `persona` (singular, como fase 1) y
--     suma tipo/numero de documento, mas las subtablas estudiante y docente.
--   * Los roles dejan de ser un enum por persona y pasan a un catalogo `rol`
--     con la tabla puente `persona_rol` (fase 1).
--   * El rol dentro de un proyecto (director, evaluador, jurado...) pasa a ser
--     el catalogo `rol_participacion`, referenciado desde `asignaciones`.
--     La vigencia sigue siendo un daterange (nunca un booleano "activo").
--
-- Nota: se conservan los nombres de columna existentes (email, creado_en...) en
-- lugar de los de fase 1 (correo, fecha_creacion) para no arrastrar la app.

-- ---------------------------------------------------------------------------
-- 1. persona (antes personas)
-- ---------------------------------------------------------------------------
alter table personas rename to persona;
alter trigger trg_personas_actualizado on persona rename to trg_persona_touch;
alter policy personas_lectura on persona rename to persona_lectura;
alter policy personas_escritura on persona rename to persona_escritura;

alter table persona
  add column tipo_documento   varchar(5),
  add column numero_documento varchar(20);

create unique index persona_documento_unico
  on persona (tipo_documento, numero_documento)
  where numero_documento is not null;

create table estudiante (
  persona_id uuid primary key references persona (id) on delete cascade,
  codigo     varchar(20) not null unique,
  semestre   smallint check (semestre is null or semestre between 1 and 12)
);

create table docente (
  persona_id  uuid primary key references persona (id) on delete cascade,
  vinculacion varchar(30),
  unidad      varchar(100)
);

-- ---------------------------------------------------------------------------
-- 2. Catalogos de roles
-- ---------------------------------------------------------------------------
create table rol (
  id     smallint generated by default as identity primary key,
  codigo varchar(30) not null unique,
  nombre varchar(60) not null
);

insert into rol (codigo, nombre) values
  ('COORDINADOR',   'Coordinador de programa'),
  ('DOCENTE',       'Docente'),
  ('ESTUDIANTE',    'Estudiante'),
  ('ADMINISTRADOR', 'Administrador del sistema');

create table rol_participacion (
  id     smallint generated by default as identity primary key,
  codigo varchar(30) not null unique,
  nombre varchar(60) not null
);

insert into rol_participacion (codigo, nombre) values
  ('DIRECTOR',             'Director'),
  ('CODIRECTOR',           'Codirector'),
  ('EVALUADOR',            'Evaluador'),
  ('JURADO',               'Jurado'),
  ('DIRECTOR_DISCIPLINAR', 'Director disciplinar'),
  ('DIRECTOR_METODOLOGICO','Director metodologico');

-- ---------------------------------------------------------------------------
-- 3. persona_rol (reemplaza roles_persona)
-- ---------------------------------------------------------------------------
create table persona_rol (
  persona_id uuid     not null references persona (id) on delete cascade,
  rol_id     smallint not null references rol (id) on delete restrict,
  creado_en  timestamptz not null default now(),
  primary key (persona_id, rol_id)
);

insert into persona_rol (persona_id, rol_id, creado_en)
select rp.persona_id, r.id, rp.creado_en
from roles_persona rp
join rol r on r.codigo = case rp.rol
  when 'estudiante'  then 'ESTUDIANTE'
  when 'evaluador'   then 'DOCENTE'
  when 'coordinador' then 'COORDINADOR'
  when 'admin'       then 'ADMINISTRADOR'
end
on conflict do nothing;

-- ---------------------------------------------------------------------------
-- 4. asignaciones: rol -> rol_participacion
-- ---------------------------------------------------------------------------
alter table asignaciones
  add column rol_participacion_id smallint references rol_participacion (id);

update asignaciones
   set rol_participacion_id = (select id from rol_participacion where codigo = 'EVALUADOR');

alter table asignaciones alter column rol_participacion_id set not null;
alter table asignaciones drop constraint asignacion_rol_evaluador;
alter table asignaciones drop column rol;

-- ---------------------------------------------------------------------------
-- 5. Funciones de ayuda sobre el nuevo modelo de roles
-- ---------------------------------------------------------------------------
create or replace function persona_actual() returns uuid
language sql stable security definer set search_path = public, pg_temp as $$
  select id from persona where usuario_id = auth.uid();
$$;

drop policy proyectos_alta on proyectos;
drop function tiene_rol(rol_usuario);

create or replace function tiene_rol(p_rol text) returns boolean
language sql stable security definer set search_path = public, pg_temp as $$
  select exists (
    select 1 from persona_rol pr
    join rol r on r.id = pr.rol_id
    where pr.persona_id = persona_actual() and r.codigo = p_rol
  );
$$;

create or replace function es_gestor() returns boolean
language sql stable security definer set search_path = public, pg_temp as $$
  select tiene_rol('COORDINADOR') or tiene_rol('ADMINISTRADOR');
$$;

create policy proyectos_alta on proyectos
  for insert to authenticated with check (
    es_gestor() or tiene_rol('ESTUDIANTE')
  );

-- ---------------------------------------------------------------------------
-- 6. RLS de las tablas nuevas
-- ---------------------------------------------------------------------------
alter table rol               enable row level security;
alter table rol_participacion enable row level security;
alter table persona_rol       enable row level security;
alter table estudiante         enable row level security;
alter table docente            enable row level security;

create policy rol_lectura on rol
  for select to anon, authenticated using (true);
create policy rol_participacion_lectura on rol_participacion
  for select to anon, authenticated using (true);

create policy persona_rol_lectura on persona_rol
  for select to authenticated using (persona_id = persona_actual() or es_gestor());
create policy persona_rol_gestion on persona_rol
  for all to authenticated using (es_gestor()) with check (es_gestor());

create policy estudiante_lectura on estudiante
  for select to authenticated using (persona_id = persona_actual() or es_gestor());
create policy estudiante_gestion on estudiante
  for all to authenticated
  using (persona_id = persona_actual() or es_gestor())
  with check (persona_id = persona_actual() or es_gestor());

create policy docente_lectura on docente
  for select to authenticated using (persona_id = persona_actual() or es_gestor());
create policy docente_gestion on docente
  for all to authenticated using (es_gestor()) with check (es_gestor());

-- ---------------------------------------------------------------------------
-- 7. Fuera el modelo viejo
-- ---------------------------------------------------------------------------
drop table roles_persona;
drop type rol_usuario;

-- ---------------------------------------------------------------------------
-- 8. Provision de persona al primer login (ahora sobre persona / persona_rol)
-- ---------------------------------------------------------------------------
do $$
begin
  if to_regclass('auth.users') is not null then
    execute $fn$
      create or replace function manejar_nuevo_usuario() returns trigger
      language plpgsql security definer set search_path = public, pg_temp as $body$
      declare v_persona uuid; v_rol smallint;
      begin
        select id into v_persona
        from persona
        where usuario_id is null and email = new.email
        limit 1;

        if v_persona is not null then
          update persona
             set usuario_id = new.id, actualizado_en = now()
           where id = v_persona;
        else
          insert into persona (usuario_id, nombres, apellidos, email)
          values (
            new.id,
            coalesce(new.raw_user_meta_data->>'given_name',
                     new.raw_user_meta_data->>'name',
                     split_part(coalesce(new.email, 'usuario'), '@', 1)),
            coalesce(new.raw_user_meta_data->>'family_name', ''),
            new.email
          )
          on conflict (usuario_id) do nothing
          returning id into v_persona;

          if v_persona is null then
            select id into v_persona from persona where usuario_id = new.id;
          end if;
        end if;

        -- Todo usuario institucional entra como estudiante; coordinador/admin se
        -- asignan despues. Sin este rol, el RLS impediria crear anteproyectos.
        if v_persona is not null then
          select id into v_rol from rol where codigo = 'ESTUDIANTE';
          insert into persona_rol (persona_id, rol_id)
          values (v_persona, v_rol)
          on conflict do nothing;
        end if;

        return new;
      end;
      $body$;
    $fn$;
  end if;
end
$$;

-- ---------------------------------------------------------------------------
-- 9. Grants para las tablas nuevas (solo si existen los roles de Supabase)
-- ---------------------------------------------------------------------------
do $$
begin
  if exists (select 1 from pg_roles where rolname = 'authenticated') then
    grant select, insert, update, delete on all tables in schema public to authenticated;
    grant select on rol, rol_participacion, persona, estudiante, docente to authenticated;
    grant select on rol, rol_participacion to anon;
    grant execute on all functions in schema public to anon, authenticated;
  end if;
end
$$;
