-- 012_sedes.sql
-- Sede como catalogo y oferta programa x sede.
--
--   * `sede`: las 7 unidades regionales de la Universidad de Cundinamarca.
--   * `programa_sede`: donde se ofrece cada programa (un programa puede estar
--     en varias sedes).
--   * `proyectos.sede_id`: sede donde se desarrollo el trabajo (nullable para
--     los historicos que no traen el dato).
--
-- Ademas unifica Zootecnia: ZOO_UBATE y ZOO_FUSAGA eran el mismo programa
-- duplicado por sede; quedan como un solo ZOO con dos sedes.

-- ---------------------------------------------------------------------------
-- 1. Catalogo de sedes
-- ---------------------------------------------------------------------------
create table sede (
  id     smallint generated by default as identity primary key,
  codigo varchar(20) not null unique,
  nombre varchar(80) not null,
  tipo   varchar(20) not null check (tipo in ('SEDE', 'SECCIONAL', 'EXTENSION')),
  activa boolean not null default true
);

insert into sede (codigo, nombre, tipo) values
  ('FUSAGASUGA', 'Fusagasugá', 'SEDE'),
  ('GIRARDOT',   'Girardot',   'SECCIONAL'),
  ('UBATE',      'Ubaté',      'SECCIONAL'),
  ('CHIA',       'Chía',       'EXTENSION'),
  ('FACATATIVA', 'Facatativá', 'EXTENSION'),
  ('SOACHA',     'Soacha',     'EXTENSION'),
  ('ZIPAQUIRA',  'Zipaquirá',  'EXTENSION')
on conflict (codigo) do update set
  nombre = excluded.nombre,
  tipo   = excluded.tipo,
  activa = true;

-- ---------------------------------------------------------------------------
-- 2. Oferta programa x sede
-- ---------------------------------------------------------------------------
create table programa_sede (
  programa_id smallint not null references programas (id) on delete cascade,
  sede_id     smallint not null references sede (id) on delete cascade,
  activa      boolean not null default true,
  primary key (programa_id, sede_id)
);
create index idx_programa_sede_sede on programa_sede (sede_id);

-- ---------------------------------------------------------------------------
-- 3. Sede del proyecto
-- ---------------------------------------------------------------------------
alter table proyectos
  add column sede_id smallint references sede (id) on update cascade;
create index idx_proyecto_sede on proyectos (sede_id);

-- ---------------------------------------------------------------------------
-- 4. Unificar Zootecnia
-- ---------------------------------------------------------------------------
insert into programas (codigo, nombre, facultad, activo)
values ('ZOO', 'Zootecnia', 'Ciencias Agropecuarias', true)
on conflict (codigo) do update set
  nombre   = excluded.nombre,
  facultad = excluded.facultad,
  activo   = excluded.activo;

update proyectos
   set programa_id = (select id from programas where codigo = 'ZOO')
 where programa_id in (
   select id from programas where codigo in ('ZOO_UBATE', 'ZOO_FUSAGA')
 );

delete from programas where codigo in ('ZOO_UBATE', 'ZOO_FUSAGA');

-- ---------------------------------------------------------------------------
-- 5. Oferta vigente por sede (fuente: ucundinamarca.edu.co/aspirante/pregrado)
-- ---------------------------------------------------------------------------
insert into programa_sede (programa_id, sede_id, activa)
select p.id, s.id, true
from (values
  ('ADM', 'FUSAGASUGA'), ('ADM', 'GIRARDOT'), ('ADM', 'FACATATIVA'),
  ('ADM', 'CHIA'),       ('ADM', 'UBATE'),    ('ADM', 'SOACHA'),
  ('CON', 'FUSAGASUGA'), ('CON', 'UBATE'),    ('CON', 'FACATATIVA'), ('CON', 'CHIA'),
  ('ZOO', 'FUSAGASUGA'), ('ZOO', 'UBATE'),
  ('MVZ', 'FUSAGASUGA'), ('MVZ', 'UBATE'),
  ('ITG', 'FUSAGASUGA'),
  ('IAS', 'GIRARDOT'),   ('IAS', 'FACATATIVA'),
  ('IAG', 'FUSAGASUGA'), ('IAG', 'FACATATIVA'),
  ('LEF', 'FUSAGASUGA'),
  ('PCD', 'SOACHA'),
  ('LCS', 'FUSAGASUGA'),
  ('IMC', 'CHIA'),
  ('ISW', 'GIRARDOT'),   ('ISW', 'SOACHA'),
  ('ISC', 'FUSAGASUGA'), ('ISC', 'CHIA'), ('ISC', 'FACATATIVA'), ('ISC', 'UBATE'),
  ('IIN', 'SOACHA'),     ('IIN', 'CHIA'),
  ('IEL', 'FUSAGASUGA'),
  ('PSI', 'FACATATIVA'),
  ('ENF', 'GIRARDOT'),
  ('MUS', 'ZIPAQUIRA')
) as oferta(programa_codigo, sede_codigo)
join programas p on p.codigo = oferta.programa_codigo
join sede s on s.codigo = oferta.sede_codigo
on conflict (programa_id, sede_id) do update set activa = true;

-- Backfill solo cuando el programa tiene una unica sede: no se inventa el dato
-- para los programas multi-sede.
update proyectos p
   set sede_id = (
     select min(ps.sede_id)
     from programa_sede ps
     where ps.programa_id = p.programa_id and ps.activa
     having count(*) = 1
   )
 where p.sede_id is null;

-- ---------------------------------------------------------------------------
-- 6. RLS de los catalogos nuevos
-- ---------------------------------------------------------------------------
alter table sede         enable row level security;
alter table programa_sede enable row level security;

create policy sede_lectura on sede
  for select to anon, authenticated using (true);
create policy programa_sede_lectura on programa_sede
  for select to anon, authenticated using (true);

-- ---------------------------------------------------------------------------
-- 7. Grants
-- ---------------------------------------------------------------------------
do $$
begin
  if exists (select 1 from pg_roles where rolname = 'authenticated') then
    grant select, insert, update, delete on all tables in schema public to authenticated;
    grant usage, select on all sequences in schema public to authenticated;
    grant select on sede, programa_sede to anon, authenticated;
    grant execute on all functions in schema public to anon, authenticated;
  end if;
end
$$;
