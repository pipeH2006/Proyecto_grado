-- 11. asignar_participacion: gestor -> permiso asignacion.gestionar
-- ---------------------------------------------------------------------------
create or replace function asignar_participacion(
  p_proyecto bigint,
  p_persona uuid,
  p_rol_participacion smallint
) returns bigint
language plpgsql security definer set search_path = public, pg_temp as $$
declare
  v_id bigint;
begin
  if not tiene_permiso('asignacion.gestionar') then
    raise exception 'Sin permiso para asignar participantes';
  end if;

  update asignaciones
     set vigencia = daterange(lower(vigencia), current_date, '[)')
   where proyecto_id = p_proyecto
     and persona_id = p_persona
     and upper_inf(vigencia);

  insert into asignaciones (
    proyecto_id, persona_id, rol_participacion_id, creada_por
  )
  values (
    p_proyecto, p_persona, p_rol_participacion, persona_actual()
  )
  returning id into v_id;

  return v_id;
end;
$$;

-- ---------------------------------------------------------------------------
-- 12. Politicas de Storage (solo si el esquema storage existe)
-- ---------------------------------------------------------------------------
do $migracion$
begin
  if to_regclass('storage.objects') is null then
    raise notice 'esquema storage ausente: se omiten politicas de documentos';
    return;
  end if;

  execute 'drop policy if exists documentos_storage_alta on storage.objects';
  execute $pol$
    create policy documentos_storage_alta on storage.objects
      for insert to authenticated
      with check (
        bucket_id = 'documentos'
        and (
          es_autor(public.documento_proyecto_id(name))
          or esta_asignado(public.documento_proyecto_id(name))
          or tiene_permiso('documento.gestionar')
        )
      );
  $pol$;

  execute 'drop policy if exists documentos_storage_edicion on storage.objects';
  execute $pol$
    create policy documentos_storage_edicion on storage.objects
      for update to authenticated
      using (
        bucket_id = 'documentos'
        and (
          es_autor(public.documento_proyecto_id(name))
          or esta_asignado(public.documento_proyecto_id(name))
          or tiene_permiso('documento.gestionar')
        )
      )
      with check (bucket_id = 'documentos');
  $pol$;

  execute 'drop policy if exists documentos_storage_borrado on storage.objects';
  execute $pol$
    create policy documentos_storage_borrado on storage.objects
      for delete to authenticated
      using (
        bucket_id = 'documentos'
        and (
          es_autor(public.documento_proyecto_id(name))
          or tiene_permiso('documento.gestionar')
        )
      );
  $pol$;
end
$migracion$;

