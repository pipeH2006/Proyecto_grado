insert into rol_permiso (rol_id, permiso_id)
select r.id, p.id
from (values
  ('ESTUDIANTE', 'proyecto.crear'),
  ('ESTUDIANTE', 'observacion.responder'),
  ('DOCENTE',    'observacion.evaluar'),
  ('DOCENTE',    'observacion.responder')
) as m(rol_codigo, permiso_codigo)
join rol r on r.codigo = m.rol_codigo
join permiso p on p.codigo = m.permiso_codigo
on conflict do nothing;

-- Coordinador y administrador conservan la paridad actual: todos los permisos.
insert into rol_permiso (rol_id, permiso_id)
select r.id, p.id
from rol r
cross join permiso p
where r.codigo in ('COORDINADOR', 'ADMINISTRADOR')
on conflict do nothing;

