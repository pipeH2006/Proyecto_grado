-- ---------------------------------------------------------------------------
-- 5. puede_ver_proyecto: gestor -> permiso proyecto.ver_todos
-- ---------------------------------------------------------------------------
create or replace function puede_ver_proyecto(p_proyecto bigint) returns boolean
language sql stable security definer set search_path = public, pg_temp as $$
  select
    exists (
      select 1 from proyectos p
      join estado e on e.id = p.estado_actual_id
      where p.id = p_proyecto and e.codigo = 'FINALIZADO'
    )
    or es_autor(p_proyecto)
    or esta_asignado(p_proyecto)
    or tiene_permiso('proyecto.ver_todos');
$$;

