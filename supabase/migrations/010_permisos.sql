-- ---------------------------------------------------------------------------
-- 2. Funciones de ayuda
-- ---------------------------------------------------------------------------
create or replace function es_admin() returns boolean
language sql stable security definer set search_path = public, pg_temp as $$
  select tiene_rol('ADMINISTRADOR');
$$;

create or replace function tiene_permiso(p_codigo text) returns boolean
language sql stable security definer set search_path = public, pg_temp as $$
  select es_admin() or exists (
    select 1
    from persona_rol pr
    join rol_permiso rp on rp.rol_id = pr.rol_id
    join permiso p on p.id = rp.permiso_id
    where pr.persona_id = persona_actual()
      and p.codigo = p_codigo
  );
$$;

create or replace function mis_permisos() returns text[]
language sql stable security definer set search_path = public, pg_temp as $$
  select case
    when es_admin() then (
      select array_agg(codigo order by grupo, orden) from permiso
    )
    else (
      select coalesce(array_agg(distinct p.codigo order by p.codigo), '{}')
      from persona_rol pr
      join rol_permiso rp on rp.rol_id = pr.rol_id
      join permiso p on p.id = rp.permiso_id
      where pr.persona_id = persona_actual()
    )
  end;
$$;

