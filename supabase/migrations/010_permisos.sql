  for insert to authenticated with check (
    tiene_permiso('proyecto.crear')
  );

drop policy if exists proyectos_edicion on proyectos;
create policy proyectos_edicion on proyectos
  for update to authenticated using (
    tiene_permiso('proyecto.editar') or (
      es_autor(id) and exists (
        select 1 from estado e
        where e.id = proyectos.estado_actual_id and e.codigo = 'BORRADOR'
      )
    )
  ) with check (
    tiene_permiso('proyecto.editar') or es_autor(id)
  );

drop policy if exists proyectos_borrado on proyectos;
create policy proyectos_borrado on proyectos
