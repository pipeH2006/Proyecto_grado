-- 010_permisos.sql
-- Configuracion de roles y permisos.
--
-- Hasta ahora los permisos estaban hardcodeados en la RLS y en los guards de
-- TypeScript con es_gestor() / tiene_rol(). Esta migracion los convierte en
-- datos: un catalogo `permiso` y la matriz `rol_permiso`. La RLS sigue siendo la
-- fuente de verdad; solo cambia de donde lee.
--
--   * `tiene_permiso(codigo)` es la funcion de ayuda que usan las politicas.
--   * ADMINISTRADOR siempre pasa (bypass anti-bloqueo): no se puede dejar al
--     sistema sin un rol capaz de restaurar la matriz.
--   * El seed de `rol_permiso` reproduce exactamente el comportamiento previo:
--     el dia 1 nadie gana ni pierde acceso.

-- ---------------------------------------------------------------------------
-- 1. Catalogo de permisos y matriz rol_permiso
-- ---------------------------------------------------------------------------
create table permiso (
  id          smallint generated by default as identity primary key,
  codigo      varchar(60) not null unique,
  nombre      varchar(100) not null,
  descripcion text,
  grupo       varchar(40) not null,
  orden       smallint not null default 0
);

create table rol_permiso (
  rol_id     smallint not null references rol (id) on delete cascade,
  permiso_id smallint not null references permiso (id) on delete cascade,
  primary key (rol_id, permiso_id)
);

